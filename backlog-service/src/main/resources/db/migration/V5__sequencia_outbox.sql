-- Desempate da ordem por chave: dois eventos do mesmo usuário podem ter o mesmo criado_em (resolução do relógio),
-- e aí os dois viravam "cabeça de fila" e saíam juntos, sem ordem garantida. A sequência é atribuída no INSERT.
ALTER TABLE outbox_eventos ADD COLUMN sequencia BIGINT GENERATED BY DEFAULT AS IDENTITY;

DROP INDEX ix_outbox_eventos_chave_pendentes;
CREATE INDEX ix_outbox_eventos_chave_pendentes ON outbox_eventos (chave, publicado_em, sequencia);
